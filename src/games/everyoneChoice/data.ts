/**
 * 모두의 선택 — question deck (rulebook: boardGameRule/모두의선택/모두의선택.md §6).
 *
 * Every question is original. Each option carries a rough "how many people
 * would pick this" weight (our own guess, not survey data). Bots treat the
 * weights as the crowd's taste: a bot's honest favourite is drawn from them,
 * and a strategic bot reads them as its forecast of everyone else.
 */

