export type SetId = "hut" | "hanok" | "palace" | "market" | "office" | "home" | "school" | "street" | "stage";
export type Costume = "nobi" | "gat" | "crown" | "suit" | "casual" | "idol";

export interface Variant {
  label: string;
  result: string;
  fx: Fx;
  tags?: string[];
  lure?: number[];
}
export interface ChoiceDef extends Variant {
  fast?: boolean;
  swap?: Variant & { tag: string };
}
export interface EchoDef {
  tag: string;
  text: string;
  fx: Fx;
}
export interface SceneDef {
  title: string;
  set: SetId;
  npc: { name: string; g: "f" | "m" };
  /** 상대역의 대사 (말풍선) */
  line: string;
  /** 지문 (자막) */
  text: string;
  choices: ChoiceDef[];
  echoes?: EchoDef[];
}
export interface EndingDef {
  id: string;
  emoji: string;
  title: string;
  text: string;
  tags?: string[];
  min?: Fx;
  /** 이 수치 이하일 때만 (99 = 제한 없음) */
  max?: Fx;
  bonus: number;
}
export interface RoleDef {
  id: string;
  name: string;
  emoji: string;
  era: "joseon" | "modern";
  blurb: string;
  start: Fx;
  costume: Costume;
  /** 기본 점수 */
  par: number;
  /** (수치 성장×4 + 엔딩 보너스)에 곱하는 배율 */
  rate: number;
  scenes: SceneDef[];
  endings: EndingDef[];
}

