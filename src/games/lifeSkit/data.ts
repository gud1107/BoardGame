const c = (label: string, result: string, fx: Fx, tags?: string[], lure?: number[]): ChoiceDef => ({ label, result, fx, ...(tags ? { tags } : {}), ...(lure ? { lure } : {}) });
const f = (label: string, result: string, fx: Fx, tags?: string[], lure?: number[]): ChoiceDef => ({ ...c(label, result, fx, tags, lure), fast: true });
const sw = (base: ChoiceDef, tag: string, label: string, result: string, fx: Fx, tags?: string[]): ChoiceDef => ({ ...base, swap: { tag, label, result, fx, ...(tags ? { tags } : {}) } });
const sc = (title: string, set: SetId, npc: string, g: "f" | "m", line: string, text: string, choices: ChoiceDef[], echoes?: EchoDef[]): SceneDef => ({
  title,
  set,
  npc: { name: npc, g },
  line,
  text,
  choices,
  ...(echoes ? { echoes } : {}),
});
const e = (tag: string, text: string, fx: Fx): EchoDef => ({ tag, text, fx });
const end = (id: string, emoji: string, title: string, text: string, bonus: number, cond: { tags?: string[]; min?: Fx; max?: Fx } = {}): EndingDef => ({ id, emoji, title, text, bonus, ...cond });

