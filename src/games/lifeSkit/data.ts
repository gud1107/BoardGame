/**
 * 인생 상황극 대본. 수치는 [💰 재산, ❤️ 관계, 🌟 명예, 😊 행복] 순서.
 *
 * - 배역마다 7장면, 장면마다 선택지 3개. `fast`(⚡ 지름길)는 눈앞의 이득이 크지만
 *   숨은 대가와 성격 변화가 따라온다.
 * - `tags` = 그 선택으로 굳어지는 성격. `swap` = 그 성격을 가진 사람에게는 선택지가
 *   이렇게 바뀐다. 장면의 `echoes` = 그 성격으로 이 장면에 들어오면 터지는 나비효과.
 * - `lure` = 고르기 전에 보이는 힌트를 실제 이득 대신 이걸로(함정 선택지).
 * - 엔딩은 위에서부터 처음 맞는 것. 마지막 엔딩은 조건 없는 기본 엔딩이어야 한다.
 * - 점수 = `par` + `rate` × (수치 성장×4 + 엔딩 보너스). 배역마다 힌트가 얼마나 정직한지·엔딩이
 *   얼마나 후한지가 달라서, Lv.1~10 셀프플레이 평균이 같은 곡선에 오도록 맞춘 값이다
 *   (LifeSkit.test.ts가 편차를 검사).
 */

