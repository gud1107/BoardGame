export const TOPIC_BY_ID: ReadonlyMap<string, Topic> = new Map(TOPICS.map((t) => [t.id, t]));

const dictCache = new Map<string, ReadonlySet<string>>();

/** 이 주제에서 확정 단어로 인정되는 모든 단어(포함 주제까지). */
export function topicDictionary(topicId: string): ReadonlySet<string> {
  const hit = dictCache.get(topicId);
  if (hit) return hit;
  const topic = TOPIC_BY_ID.get(topicId);
  const set = new Set<string>();
  if (topic) {
    for (const word of topic.words) set.add(word);
    for (const sub of topic.includes ?? []) for (const word of TOPIC_BY_ID.get(sub)?.words ?? []) set.add(word);
  }
  dictCache.set(topicId, set);
  return set;
}

/** 봇이 쓰는 단어 목록 — 그 주제 자체의 단어만(포함 주제 제외), 중복 없이. */
export function topicWordList(topicId: string): readonly string[] {
  return [...new Set(TOPIC_BY_ID.get(topicId)?.words ?? [])];
}
