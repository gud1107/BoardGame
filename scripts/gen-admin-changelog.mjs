// Regenerates src/constants/adminChangelog.generated.ts — the "자동 기록"
// rows of the admin hub's 🗒 변경 기록 tab. Every commit whose subject uses
// an admin-only scope — feat(admin), fix(visitors), tune(analytics), … —
// becomes one row, so admin work shows up there without anyone editing a
// file by hand. Runs as `prebuild` (so every deploy picks up new commits)
// and by hand: npm run gen:admin-changelog
//
// Korean text: add an `Admin-Ko:` line anywhere in the commit message body
// (e.g. `Admin-Ko: 월별 통계 탭 추가`) and the tab shows it instead of
// the English subject. Older commits are translated in ADMIN_COMMIT_KO
// (src/constants/adminChangelog.ts).
//
// Rows already in the generated file are kept and merged by commit hash:
// Vercel builds from a shallow clone, so the local git log may only reach the
// last few commits, and older rows must not disappear. If git is unavailable
// the existing file is left untouched.
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const OUT = "src/constants/adminChangelog.generated.ts";
const SCOPES = ["admin", "visitors", "analytics"];
const SUBJECT = new RegExp(String.raw`^(\w+)\((${SCOPES.join("|")})\)!?:\s*(.+)$`);
/** docs/test/chore commits don't change what an admin sees. */
const SKIP_TYPES = new Set(["docs", "test", "chore", "ci"]);
const TYPE_MAP = { feat: "FEAT", fix: "FIX" }; // everything else → IMPROVE

const existing = new Map();
if (existsSync(OUT)) {
  const m = readFileSync(OUT, "utf8").match(/= (\[[\s\S]*\]);/);
  if (m) for (const row of JSON.parse(m[1])) existing.set(row.hash, row);
}

let log;
try {
  // %x1e ends each record; the last field is the raw body, searched for an
  // `Admin-Ko:` line anywhere (git's own trailer parsing only reads the final
  // paragraph, which is usually Co-Authored-By).
  log = execSync("git log --format=%h%x09%cs%x09%s%x09%b%x1e", {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
} catch {
  console.warn("gen-admin-changelog: git log unavailable — keeping the existing file");
  process.exit(0);
}

for (const record of log.split("\x1e")) {
  const [hash, date, subject, ...bodyParts] = record.trim().split("\t");
  const m = subject?.match(SUBJECT);
  if (!m || SKIP_TYPES.has(m[1])) continue;
  const row = { hash, date, type: TYPE_MAP[m[1]] ?? "IMPROVE", scope: m[2], desc: m[3].trim() };
  const ko = bodyParts.join("\t").match(/^Admin-Ko:[ \t]*(.+)$/m)?.[1];
  const koText = ko?.trim() || existing.get(hash)?.ko;
  existing.set(hash, koText ? { ...row, ko: koText } : row);
}

// Same-day rows follow git log order (newest first); rows the shallow log no
// longer reaches keep their previous relative order after those.
const logOrder = new Map(log.split("\x1e").map((r, i) => [r.trim().split("\t")[0], i]));
const prevOrder = new Map([...existing.keys()].map((h, i) => [h, i]));
const rank = (h) => logOrder.get(h) ?? logOrder.size + prevOrder.get(h);
const rows = [...existing.values()].sort((a, b) => b.date.localeCompare(a.date) || rank(a.hash) - rank(b.hash));
const body = `// GENERATED by scripts/gen-admin-changelog.mjs — do not edit by hand.
import type { AdminCommitEntry } from "./adminChangelog";

export const ADMIN_COMMITS: AdminCommitEntry[] = ${JSON.stringify(rows, null, 2)};
`;
const prev = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
if (prev.replace(/\r\n/g, "\n") !== body) {
  writeFileSync(OUT, body);
  console.log(`gen-admin-changelog: wrote ${rows.length} rows`);
}
